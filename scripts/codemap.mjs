// Generates .claude/codemap.md: per-service image/port/routes/env vars (read from source) + file tree.
// Usage: npm run codemap (also runs in .husky/pre-commit; CI fails if the committed file is stale)

import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname } from 'node:path';

const OUT = '.claude/codemap.md';
const SERVICES = ['poll', 'result', 'worker'];
const SKIP = /(^|\/)package-lock\.json$|\.(pdf|zip|css)$|^\.claude\/codemap\.md$/;
const ENV =
  /(?:os\.getenv\(|os\.environ\[|os\.environ\.get\(|System\.getenv\(|process\.env\[)\s*['"]([A-Z0-9_]+)['"]|process\.env\.([A-Z0-9_]+)/g;
const ROUTE = /(?:@app\.route\(|app\.get\(|createContext\()\s*['"](\/[^'"]*)['"]/g;

// shortcut: tracked files only, so `git add` new files before committing; no untracked listing
const files = execFileSync('git', ['ls-files'], { encoding: 'utf8' })
  .split('\n')
  .filter((f) => f && !SKIP.test(f) && existsSync(f))
  .sort();

const grab = (src, re) => [...src.matchAll(re)].map((m) => m[1] ?? m[2]);
const list = (a) => (a.length ? a.map((x) => `\`${x}\``).join(', ') : '-');

const rows = SERVICES.map((svc) => {
  const dir = `poll-application/${svc}/`;
  const docker = files.includes(`${dir}Dockerfile`) ? readFileSync(`${dir}Dockerfile`, 'utf8') : '';
  const image =
    docker
      .match(/^FROM\s+(\S+)/gm)
      ?.at(-1)
      ?.replace('FROM ', '')
      .replace(/@sha256:\w+$/, '') ?? '-'; // the digest pin changes with every Dependabot bump
  const port = docker.match(/^EXPOSE\s+(\d+)/m)?.[1] ?? '-';
  const src = files
    .filter((f) => f.startsWith(dir) && /\.(py|js|java)$/.test(f))
    .map((f) => readFileSync(f, 'utf8'))
    .join('\n');
  const routes = [...new Set(grab(src, ROUTE))];
  const env = [...new Set(grab(src, ENV))];
  return `| **${svc}** | ${image} | ${port} | ${list(routes)} | ${list(env)} |`;
});

const tree = {};
for (const f of files) (tree[dirname(f)] ??= []).push(basename(f));

const lines = [
  '# Code Map',
  '',
  '> Generated by `npm run codemap`. Do not edit.',
  '',
  '## Services (from source)',
  '',
  '| Service | Runtime image | Port | Routes | Env vars |',
  '| --- | --- | --- | --- | --- |',
  ...rows,
  '',
  'redis, postgres: see `docker-compose.yml` (internal only).',
  '',
  '## Files',
  '',
  ...Object.entries(tree).map(([dir, names]) => `- \`${dir}/\`: ${names.join(', ')}`),
  '',
];

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join('\n'));
try {
  execFileSync('npx', ['--no-install', 'prettier', '--write', OUT], { stdio: 'ignore' });
} catch {
  // prettier missing: CI format check will flag it
}
console.log(`Wrote ${OUT} (${files.length} files).`);
